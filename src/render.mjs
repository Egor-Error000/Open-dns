// Single source for server DNS, SNI and Windows YogaDNS policies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {serverConfig} from './config.mjs';
export {serverConfig, requireDeploymentConfig} from './config.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
export const catalog = JSON.parse(fs.readFileSync(path.join(here, '../config/services.json'), 'utf8'));
const hostnamePattern = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$/;
export function rulesFor(profiles) {
  const exact = new Set(), suffix = new Set();
  for (const id of profiles) {
    if (!Object.hasOwn(catalog, id)) throw new Error(`Unknown profile: ${id}`);
    for (const kind of ['exact', 'suffix']) for (const name of catalog[id][kind]) {
      if (name.length > 253 || !hostnamePattern.test(name)) throw new Error(`Invalid hostname: ${name}`);
      (kind === 'exact' ? exact : suffix).add(name);
    }
  }
  if (exact.has(serverConfig.dohHostname) || [...suffix].some(s => serverConfig.dohHostname === s || serverConfig.dohHostname.endsWith('.' + s))) throw new Error('DoH must not redirect itself');
  return {exact: [...exact].sort(), suffix: [...suffix].sort()};
}
export function selected(name, rules) {
  name = name.toLowerCase().replace(/\.$/, '');
  return rules.exact.includes(name) || rules.suffix.some(s => name === s || name.endsWith('.' + s));
}
export function render(profiles) {
  const rules = rulesFor(profiles);
  const dns = ['-- Generated by src/render.mjs; edit config/services.json.', 'setLocal("127.0.0.1:5300")', 'setACL({"127.0.0.0/8"})', 'addDOHLocal("127.0.0.1:8443", "/etc/dnsdist/cert.pem", "/etc/dnsdist/key.pem", {"/dns-query"}, {minTLSVersion="tls1.2"})', 'newServer({address="1.1.1.1:53", name="cloudflare"})', 'newServer({address="9.9.9.9:53", name="quad9"})'];
  // dnsdist 1.8 uses SuffixMatchNodeRule; QNameSuffixRule requires 1.9.
  for (const kind of ['exact', 'suffix']) for (const name of rules[kind]) {
    if (kind === 'suffix') dns.push(`local suffix = newSuffixMatchNode(); suffix:add(newDNSName("${name}."))`);
    const rule = kind === 'exact' ? `QNameRule("${name}.")` : 'SuffixMatchNodeRule(suffix)';
    dns.push(`addAction(AndRule({${rule}, QTypeRule(1)}), SpoofAction("${serverConfig.ipv4}", {ttl=60}))`);
    for (const type of [28, 64, 65]) dns.push(`addAction(AndRule({${rule}, QTypeRule(${type})}), RCodeAction(0))`);
  }
  const nginx = ['# Generated by src/render.mjs.', `log_format smartdns escape=json '{"time":"$time_iso8601","client":"$remote_addr","sni":"$ssl_preread_server_name","upstream":"$upstream_addr","status":$status,"sent":$bytes_sent,"received":$bytes_received,"seconds":$session_time}';`, 'map $ssl_preread_server_name $smartdns_target {', `    ${serverConfig.dohHostname} 127.0.0.1:8443;`];
  for (const name of rules.exact) nginx.push(`    ${name} ${name}:443;`);
  // Match only validated suffixes, then resolve the original SNI via public DNS.
  for (const name of rules.suffix) nginx.push(`    ~*^(?:[a-z0-9-]+\\.)*${name.replaceAll('.', '\\.')}\\.?$ $ssl_preread_server_name:443;`);
  nginx.push('    default 127.0.0.1:9;', '}', 'server {', '    listen 443;', '    ssl_preread on;', '    access_log /var/log/nginx/smartdns-stream.log smartdns;', '    resolver 1.1.1.1 9.9.9.9 valid=60s ipv6=off;', '    resolver_timeout 5s;', '    proxy_pass $smartdns_target;', '    proxy_connect_timeout 8s;', '    proxy_timeout 600s;', '}');
  const hostnames = [...new Set([...rules.exact, ...rules.suffix.flatMap(s => [s, `*.${s}`])])];
  const masks = hostnames.join(';');
  const yoga = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n<YogaDnsProfile file_format="1" product_id="1" product_min_version="127000">\n  <Settings ignore_rule_if_interface_down="1" blockTcpPort53="1" clearDnsCache="1" ttlMin="0" ttlMax="2147483647" captivePortalDetection="0" interceptOthers="0" />\n  <Rule name="SmartDNS selected services" enabled="1" dnssec_local_validation="0" dnssec_reject_unsigned="0" hostnames="${masks}" action="process_server" action_id="2000" interface_id="" interface_id_type="id" interface_name="" />\n  <Rule name="Default" enabled="1" dnssec_local_validation="0" dnssec_reject_unsigned="0" hostnames="*" action="bypass" action_id="" interface_id="" interface_id_type="id" interface_name="" />\n  <DnsServer id="2000" name="SmartDNS" protocol="doh" af="2" ip="${serverConfig.ipv4}" dnssec_supported="0" doh_host_name="${serverConfig.dohHostname}" doh_path="/dns-query" />\n</YogaDnsProfile>\n`;
  const guide = fs.readFileSync(path.join(here, '../client/setup.template.html'), 'utf8')
    .replaceAll('__DOH_URL__', `https://${serverConfig.dohHostname}/dns-query`)
    .replaceAll('__SERVER_IPV4__', serverConfig.ipv4)
    .replace('__SERVICE_HOSTS__', JSON.stringify(hostnames));
  return {'dnsdist.conf': dns.join('\n') + '\n', 'nginx-stream.conf': nginx.join('\n') + '\n', 'YogaDNS-SmartDNS.xml': yoga, 'YogaDNS-hostnames.txt': hostnames.join('\n') + '\n', 'setup.html': guide, 'services.json': JSON.stringify(catalog, null, 2) + '\n', 'server.json': JSON.stringify(serverConfig, null, 2) + '\n', 'active-profiles.json': JSON.stringify(profiles) + '\n'};
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = process.argv[2];
  if (!output) throw new Error('Usage: node src/render.mjs OUTPUT [baseline openai cursor claude openrouter grok]');
  const profiles = process.argv.slice(3);
  const enabled = profiles.length ? profiles : Object.keys(catalog);
  fs.mkdirSync(output, {recursive: true});
  for (const [name, data] of Object.entries(render(enabled))) fs.writeFileSync(path.join(output, name), data);
  console.log(JSON.stringify({output, profiles: enabled, rules: rulesFor(enabled)}));
}
